pub struct Launch {
    pub argv: Vec<String>,
    pub env: Vec<String>,
    pub integrated: bool,
}

fn write_script(name: &str, content: &str) -> Option<PathBuf> {
    let p = runtime_dir().join(name);
    match write_atomic(&p, content.as_bytes()) {
        Ok(()) => Some(p),
        Err(e) => {
            log!("cannot write {}: {e}", p.display());
            None
        }
    }
}

pub fn launch(shell_path: &str) -> Launch {
    let argv = |extra: &[String]| -> Vec<String> {
        std::iter::once(shell_path.to_string()).chain(extra.iter().cloned()).collect()
    };
    let plain = Launch { argv: argv(&[]), env: Vec::new(), integrated: false };
    match Shell::of(shell_path) {
        Shell::Bash => write_script("bashrc", BASHRC).map_or(plain, |rc| Launch {
            argv: argv(&["--rcfile".into(), rc.to_string_lossy().into_owned()]),
            env: Vec::new(),
            integrated: true,
        }),
        Shell::Zsh => write_script("zsh/.zshenv", ZSHENV).map_or(plain, |rc| {
            let mut env = vec![format!("ZDOTDIR={}", rc.parent().unwrap_or(&rc).display())];
            if let Ok(orig) = std::env::var("ZDOTDIR") {
                env.push(format!("SHELLMAN_ZDOTDIR={orig}"));
            }
            Launch { argv: argv(&[]), env, integrated: true }
        }),
        Shell::Fish => write_script("init.fish", FISH_INIT).map_or(plain, |rc| Launch {
            argv: argv(&["--init-command".into(), format!("source '{}'", rc.display())]),
            env: Vec::new(),
            integrated: true,
        }),
        Shell::Posix | Shell::Csh | Shell::Unknown => {
            log!("shell {shell_path}: no SEL variable, no folder following");
            plain
        }
    }
}

pub fn utf8_locale() -> bool {
    ["LC_ALL", "LC_CTYPE", "LANG"].iter()
        .find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
        .is_some_and(|v| {
            let v = v.to_ascii_lowercase();
            v.contains("utf-8") || v.contains("utf8")
        })
}

fn invisible(c: char) -> bool {
    c.is_control()
        || matches!(c as u32, 0xAD | 0x061C | 0x180E | 0x200B..=0x200F | 0x2028..=0x202E
                    | 0x2060..=0x206F | 0xFEFF | 0xFFF9..=0xFFFB)
}

fn strict(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || "/._-".contains(c))
}

fn plain(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || "/._-+,:@%".contains(c))
}

fn ansi_c(bytes: &[u8]) -> String {
    let mut out = String::from("$'");
    for &b in bytes {
        if (b.is_ascii_graphic() || b == b' ') && b != b'\'' && b != b'\\' {
            out.push(b as char);
        } else {
            out.push_str(&format!("\\x{b:02x}"));
        }
    }
    out.push('\'');
    out
}

fn fish_bytes(bytes: &[u8]) -> String {
    let mut out = String::new();
    let mut run = String::new();
    let flush = |run: &mut String, out: &mut String| {
        if !run.is_empty() {
            out.push('\'');
            out.push_str(run);
            out.push('\'');
            run.clear();
        }
    };
    for &b in bytes {
        if (b.is_ascii_graphic() || b == b' ') && b != b'\'' && b != b'\\' {
            run.push(b as char);
        } else {
            flush(&mut run, &mut out);
            out.push_str(&format!("\\X{b:02X}"));
        }
    }
    flush(&mut run, &mut out);
    out
}

pub fn quote(shell: Shell, path: &Path, utf8: bool) -> Option<String> {
    if !path.is_absolute() {
        return None;
    }
    let bytes = path.as_os_str().as_bytes();
    let text = std::str::from_utf8(bytes).ok()
        .filter(|s| !s.chars().any(invisible) && (utf8 || s.is_ascii()));
    let out = match (shell, text) {
        (Shell::Unknown, Some(s)) if strict(s) => s.to_string(),
        (Shell::Unknown, _) => return None,
        (_, Some(s)) if plain(s) => s.to_string(),
        (Shell::Fish, Some(s)) => format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'")),
        (Shell::Fish, None) => fish_bytes(bytes),
        (Shell::Csh, Some(s)) if s.contains('!') => return None,
        (_, Some(s)) => format!("'{}'", s.replace('\'', "'\\''")),
        (Shell::Bash | Shell::Zsh, None) => ansi_c(bytes),
        (Shell::Posix | Shell::Csh, None) => return None,
    };
    (!out.chars().any(invisible)).then_some(out)
}

pub fn words(shell: Shell, paths: &[PathBuf], utf8: bool) -> Option<String> {
    let mut out = String::new();
    for p in paths {
        out.push_str(&quote(shell, p, utf8)?);
        out.push(' ');
    }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::ffi::OsStr;

    fn q(shell: Shell, bytes: &[u8]) -> Option<String> {
        quote(shell, Path::new(OsStr::from_bytes(bytes)), true)
    }

    #[test]
    fn plain_names_stay_plain() {
        assert_eq!(q(Shell::Bash, b"/tmp/photo.jpg").as_deref(), Some("/tmp/photo.jpg"));
    }

    #[test]
    fn shell_metacharacters_are_single_quoted() {
        assert_eq!(q(Shell::Bash, b"/tmp/a; rm -rf ~ & $(x) `y` |z").as_deref(),
                   Some("'/tmp/a; rm -rf ~ & $(x) `y` |z'"));
        assert_eq!(q(Shell::Bash, b"/tmp/l'ete").as_deref(), Some("'/tmp/l'\\''ete'"));
    }

    #[test]
    fn relative_paths_are_refused() {
        assert_eq!(q(Shell::Bash, b"-rf"), None);
        assert_eq!(q(Shell::Bash, b"+:!rm"), None);
    }

    #[test]
    fn control_characters_are_never_emitted() {
        for shell in [Shell::Bash, Shell::Zsh, Shell::Fish, Shell::Posix, Shell::Csh, Shell::Unknown] {
            for name in [&b"/tmp/a\x1b\x05b"[..], b"/tmp/a\nb", b"/tmp/a\rb", b"/tmp/\x03",
                         b"/tmp/\xff\xfe", "/tmp/a\u{202e}b".as_bytes(), "/tmp/\u{200b}".as_bytes()] {
                if let Some(out) = q(shell, name) {
                    assert!(out.chars().all(|c| !invisible(c)), "{shell:?} {out:?}");
                }
            }
        }
    }

    #[test]
    fn escapes_per_shell() {
        assert_eq!(q(Shell::Bash, b"/tmp/a\x1bb'c").as_deref(), Some("$'/tmp/a\\x1bb\\x27c'"));
        assert_eq!(q(Shell::Fish, b"/tmp/a\x1bb").as_deref(), Some("'/tmp/a'\\X1B'b'"));
        assert_eq!(q(Shell::Fish, b"/tmp/a\\'b").as_deref(), Some("'/tmp/a\\\\\\'b'"));
        assert_eq!(q(Shell::Posix, b"/tmp/a\x1bb"), None);
        assert_eq!(q(Shell::Posix, b"/tmp/a!b").as_deref(), Some("'/tmp/a!b'"));
        assert_eq!(q(Shell::Csh, b"/tmp/a!b"), None);
        assert_eq!(q(Shell::Unknown, b"/tmp/photo-1.jpg").as_deref(), Some("/tmp/photo-1.jpg"));
        assert_eq!(q(Shell::Unknown, b"/tmp/a,b"), None);
        assert_eq!(q(Shell::Unknown, b"/tmp/a b"), None);
    }

    #[test]
    fn shells_read_back_the_exact_name() {
        let names: [&[u8]; 6] = [b"/tmp/a; rm -rf ~ & $(x) `y` |z", b"/tmp/l'ete \\ \"q\"",
                                 b"/tmp/a\x1b\x05\r\nb", "/tmp/été \u{202e}x".as_bytes(),
                                 b"/tmp/\xff\xfe", b"/tmp/*?[a]{b,c}~#!%"];
        let mut runs = std::collections::BTreeMap::<&str, usize>::new();
        for name in names {
            for (shell, prog) in [(Shell::Bash, "bash"), (Shell::Zsh, "zsh"), (Shell::Fish, "fish"),
                                  (Shell::Posix, "sh"), (Shell::Posix, "dash"), (Shell::Posix, "ksh"),
                                  (Shell::Posix, "mksh"), (Shell::Csh, "tcsh"), (Shell::Csh, "csh")] {
                let Some(word) = q(shell, name) else { continue };
                let Ok(out) = std::process::Command::new(prog)
                    .args(["-c", &format!("printf %s {word}")])
                    .output() else { continue };
                assert_eq!(out.stdout, name, "{prog} {word}");
                *runs.entry(prog).or_default() += 1;
            }
        }
        eprintln!("relectures par shell : {runs:?}");
    }

    #[test]
    fn non_ascii_needs_utf8_locale() {
        let p = Path::new("/tmp/été");
        assert_eq!(quote(Shell::Bash, p, true).as_deref(), Some("'/tmp/été'"));
        assert_eq!(quote(Shell::Bash, p, false).as_deref(), Some("$'/tmp/\\xc3\\xa9t\\xc3\\xa9'"));
    }
}
