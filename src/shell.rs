pub const CD_KEY: &str = "\x1b[24;8~";

#[derive(Clone, Copy, PartialEq, Debug)]
pub enum Shell {
    Bash,
    Zsh,
    Fish,
    Posix,
    Csh,
    Unknown,
}

impl Shell {
    pub fn of(path: &str) -> Shell {
        match Path::new(path).file_name().and_then(|n| n.to_str()) {
            Some("bash") => Shell::Bash,
            Some("zsh") => Shell::Zsh,
            Some("fish") => Shell::Fish,
            Some("sh" | "dash" | "ash" | "ksh" | "ksh93" | "mksh" | "lksh" | "oksh" | "pdksh"
                 | "yash" | "posh" | "osh" | "rbash") => Shell::Posix,
            Some("csh" | "tcsh") => Shell::Csh,
            _ => Shell::Unknown,
        }
    }

    pub fn sel_variable(self) -> Option<&'static str> {
        match self {
            Shell::Bash | Shell::Zsh => Some("\"${SEL[@]}\""),
            Shell::Fish => Some("$SEL"),
            _ => None,
        }
    }
}

pub fn runtime_dir() -> PathBuf {
    glib::user_runtime_dir().join("shellman")
}

pub fn runtime_file(prefix: &str) -> PathBuf {
    static N: AtomicU32 = AtomicU32::new(0);
    let n = N.fetch_add(1, Ordering::Relaxed);
    runtime_dir().join(format!("{prefix}-{}-{n}", std::process::id()))
}

pub fn remove_stale_files() {
    let Ok(entries) = std::fs::read_dir(runtime_dir()) else { return };
    for e in entries.flatten() {
        let name = e.file_name();
        let Some(name) = name.to_str() else { continue };
        let base = name.strip_suffix(".tmp").unwrap_or(name);
        let mut parts = base.split('-');
        let (Some(prefix), Some(pid), Some(_), None) = (parts.next(), parts.next(), parts.next(), parts.next())
        else { continue };
        let Ok(pid) = pid.parse::<u32>() else { continue };
        if ["sel", "cd", "state"].contains(&prefix) && pid != std::process::id()
            && !Path::new(&format!("/proc/{pid}")).exists()
        {
            let _ = std::fs::remove_file(e.path());
        }
    }
}

pub fn write_atomic(file: &Path, content: &[u8]) -> std::io::Result<()> {
    if let Some(dir) = file.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let tmp = file.with_extension("tmp");
    std::fs::write(&tmp, content)?;
    std::fs::rename(&tmp, file)
}

